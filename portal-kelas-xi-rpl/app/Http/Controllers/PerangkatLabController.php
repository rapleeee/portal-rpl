    /**
     * Hitung ringkasan statistik perangkat lab komputer.
     *
     * @param array<int, array<string, mixed>> $devices
     * @return array<string, int>
     */
    public function getStatistics(array $devices): array
    {
        $total = count($devices);
        $baik = 0;
        $perbaikan = 0;
        $rusak = 0;

        foreach ($devices as $item) {
            $kondisi = $item['kondisi'] ?? '';
            if ($kondisi === 'Baik') {
                $baik++;
            } elseif ($kondisi === 'Perlu Perbaikan') {
                $perbaikan++;
            } elseif ($kondisi === 'Rusak') {
                $rusak++;
            }
        }

        return [
            'total' => $total,
            'baik' => $baik,
            'perbaikan' => $perbaikan,
            'rusak' => $rusak,
        ];
    }
